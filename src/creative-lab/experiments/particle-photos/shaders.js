export const vertex=`#version 300 es
precision highp float;
precision highp int;
layout(location=0) in vec2 anchor;
layout(location=1) in vec4 info;
layout(location=2) in vec4 extra;
uniform vec2 canvasSize,grid,pointer;
uniform vec4 view;
uniform float radius,displacement,scatter,original,engagement,markSize,contrast;
uniform int mode;
out vec2 markUV,photoUV;
out vec4 detail;
out vec2 randomMark;
void main(){
 vec2 corner=vec2(gl_VertexID&1,gl_VertexID>>1)-.5;
 float r=info.w,q=extra.x,dark=pow(clamp(1.-info.x,0.,1.),contrast);
 vec2 delta=(anchor-pointer)*view.zw;float dist=length(delta),reach=min(view.z,view.w)*radius*.01*(.83+q*.3);
 float field=clamp((1.-dist/reach)/.62,0.,1.);field=field*field*(3.-2.*field)*engagement;
 float resolve=mix(field*(mode==0?.74:1.),1.,original);
 vec2 direction=delta/max(1.,dist),tangent=vec2(-direction.y,direction.x);
 float force=field*(1.-field)*displacement*min(view.z,view.w)/500.*(1.-original);
 float spread=scatter*(1.-original)*min(view.z,view.w)*(.22+q*.72);
 vec2 shift=(direction+tangent*(q-.5))*force+vec2(cos(r*6.2831853),sin(r*6.2831853))*spread;
 vec2 cell=view.zw/grid;
 vec2 jitter=vec2(r-.5,q-.5)*cell*.66*(1.-resolve);
 float angle=mix(info.z+(r-.5)*.65+(q-.5)*scatter*5.,0.,resolve);
 mat2 rotation=mat2(cos(angle),sin(angle),-sin(angle),cos(angle));
 vec2 size=mix(cell*(.8+dark*1.6)*markSize,cell*1.006,resolve);
 vec2 position=view.xy+anchor*view.zw+jitter+shift+rotation*(corner*size);
 gl_Position=vec4((position/canvasSize*2.-1.)*vec2(1.,-1.),0.,1.);
 markUV=corner+.5;photoUV=anchor+corner/grid;
 detail=vec4(dark,info.y,resolve,original);randomMark=vec2(r,q);
}`;
export const fragment=`#version 300 es
precision highp float;
precision highp int;
uniform sampler2D photo;
uniform vec3 ink;
uniform int mode;
uniform float scatter;
in vec2 markUV,photoUV;
in vec4 detail;
in vec2 randomMark;
out vec4 result;
void main(){
 vec2 p=markUV-.5;float r=randomMark.x,q=randomMark.y,dark=detail.x,resolve=detail.z;
 float shape;
 if(q>.84)shape=min(length(p*vec2(1.2,4.8)),length(p*vec2(4.8,1.3)));
 else if(q>.37)shape=length(p*vec2(1.05,3.7));
 else shape=length(p*vec2(1.5,1.7));
 shape+=sin(p.x*36.+r*18.)*.025;
 float mark=1.-smoothstep(.34,.49,shape);
 float selected=step(r,.04+dark*.94+detail.y*.4+resolve*.24);
 float alpha=mix(mark*selected*(.36+dark*.64),1.,resolve);
 vec3 color=texture(photo,clamp(photoUV,0.,1.)).rgb;
 float gray=dot(color,vec3(.2126,.7152,.0722));
 vec3 etched=vec3(gray*.96,gray*.94,gray*.88);
 vec3 resolved=mode==0?mix(etched,color,detail.w):color;
 float tone=resolve;
 if(mode==1)tone=max(tone,scatter*.7);
 if(mode==1&&scatter>.05)alpha*=1.-scatter*.15*(1.-detail.w);
 if(alpha<.01)discard;
 result=vec4(mix(ink,resolved,tone),alpha);
}`;
